# interpreter.py Математический интерпретатор
# Запрашиваем у пользователя арифметическое выражение, например "1 + 1".
expression = input("Expression: ")

# Разбиваем строку по пробелам на три части: x, y, z.
# "1 + 1" → ["1", "+", "1"]
x, y, z = expression.split()

# Преобразуем x и z из строк в целые числа (int).
# y оставляем строкой — это оператор (+, -, *, /).
x = int(x)
z = int(z)

# Выбираем операцию в зависимости от того, что ввёл пользователь.
if y == "+":
    result = x + z
    # Сложение: 1 + 1 → 2

elif y == "-":
    result = x - z
    # Вычитание: 5 - 2 → 3

elif y == "*":
    result = x * z
    # Умножение: 3 * 4 → 12

elif y == "/":
    result = x / z
    # Деление: 6 / 2 → 3.0
    # В Python 3 оператор / ВСЕГДА даёт float, даже если делится нацело.

# Выводим результат с одним знаком после запятой.
# :.1f — формат: число с плавающей точкой, 1 знак после точки.
# Например: 2 → "2.0", 3.5 → "3.5", 0.3333... → "0.3".
print(f"{result:.1f}")